type Mode = "sync" | "async";

// One example written twice: the sync and async clients take the same arguments.
const pair = (file: string, sync: string, async: string): CodeTab[] => [
  { id: "sync", label: "Sync", file, code: sync },
  { id: "async", label: "Async", file, code: async },
];

const QUESTIONS = `        questions={
            "billing": Noul(instructions="Is this ticket about billing?"),
            "tone": Choice(
                instructions="What is the customer's tone?",
                criteria={"calm": None, "frustrated": None, "angry": None},
            ),
            "urgency": Score(
                instructions="How urgent is this ticket?",
                criteria=["can wait", "this week", "today"],
            ),
        },`;

const QUICKSTART = pair(
  "main.py",
  `
from typesafe_sdk import Choice, Noul, Score
from jevdb import JevDB

with JevDB(group_id="support-bot") as jevdb:
    response = jevdb.system_one(
        state={"document": "I was charged twice. Please fix this ASAP."},
${QUESTIONS}
    )

print(response.nouls["billing"].noul)
print(response.choices["tone"].choice)
print(response.scores["urgency"].score)
`,
  `
import asyncio

from typesafe_sdk import Choice, Noul, Score
from jevdb import AsyncJevDB


async def main() -> None:
    async with AsyncJevDB(group_id="support-bot") as jevdb:
        response = await jevdb.system_one(
            state={"document": "I was charged twice. Please fix this ASAP."},
${QUESTIONS.replace(/^/gm, "    ")}
        )

    print(response.nouls["billing"].noul)
    print(response.choices["tone"].choice)
    print(response.scores["urgency"].score)


asyncio.run(main())
`,
);

const CLIENT_ARGS = `
    api_key="jdb_live_…",         # JevDB key         · default: env JEVDB_API_KEY
    jev_api_key="sk-…",           # Jev (TypeSafe) key · default: env TYPESAFE_API_KEY
    base_url="https://…",         # where JevDB runs  · default: env JEVDB_URL, else http://localhost:3000
    user_id="user_482",           # optional, attached to every call
    group_id="support-bot",       # optional, attached to every call
    tags=["prod"],                # optional, attached to every call
    model="jev-1.13.0",           # optional default Jev model (pin it!)
    jev_client=None,              # optional: bring your own TypeSafe client instead
    on_error=None,                # optional: called if a log fails to send (default: print a warning)
)`;

const CLIENT = pair(
  "client.py",
  `
from jevdb import JevDB

jevdb = JevDB(${CLIENT_ARGS}
`,
  `
from jevdb import AsyncJevDB

jevdb = AsyncJevDB(${CLIENT_ARGS}
`,
);

const PER_CALL = pair(
  "per_call.py",
  `
with JevDB(group_id="support-bot", tags=["prod"]) as jevdb:   # stays the same for the app
    response = jevdb.system_one(
        state=ticket.text,
        questions=QUESTIONS,
        user_id=current_user.id,        # changes every call
        decision_id=ticket.id,          # your own id (optional)
        model="jev-1.13.0",             # TypeSafe's own options still work
        timeout=10,
    )
`,
  `
async with AsyncJevDB(group_id="support-bot", tags=["prod"]) as jevdb:
    response = await jevdb.system_one(
        state=ticket.text,
        questions=QUESTIONS,
        user_id=current_user.id,
        decision_id=ticket.id,
        model="jev-1.13.0",
        timeout=10,
    )
`,
);

const IDS = pair(
  "ids.py",
  `
response = jevdb.system_one(state=..., questions=...)
decision_id = jevdb.id_of(response)     # generated by the SDK (UUID)

# or bring your own, so grading later is just a lookup:
jevdb.system_one(state=..., questions=..., decision_id=ticket.id)
`,
  `
response = await jevdb.system_one(state=..., questions=...)
decision_id = jevdb.id_of(response)

await jevdb.system_one(state=..., questions=..., decision_id=ticket.id)
`,
);

const ERRORS = pair(
  "errors.py",
  `
from typesafe_sdk import TypeSafeAPIError

try:
    response = jevdb.system_one(state=..., questions=...)
except TypeSafeAPIError as err:   # logged to JevDB with its status, then re-raised
    print(err.status, err.body)

jevdb.flush()   # wait for pending logs (the with-block does this for you)
`,
  `
from typesafe_sdk import TypeSafeAPIError

try:
    response = await jevdb.system_one(state=..., questions=...)
except TypeSafeAPIError as err:
    print(err.status, err.body)

await jevdb.flush()   # the async with-block does this for you
`,
);

