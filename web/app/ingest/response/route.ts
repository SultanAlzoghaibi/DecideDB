// POST /ingest/response — the JS and Python SDKs send one Jev call here
// (the request they sent to Jev + the response they got back).
//
// It runs only on the server, so later it's the place that writes to Postgres.

// One Jev call, as sent by the SDKs (see sdk/python/README.md → "What gets sent to DecisionDB").
type IngestPayload = {
  id: string; // decision id, generated by the SDK (used to grade later + dedupe retries)
  started_at: string; // when the Jev call started (client clock, UTC)
  latency_ms?: number;
  status: number | null; // Jev's HTTP status
  error?: string | null; // set when the Jev call failed
  user_id?: string | null;
  group_id?: string | null;
  tags?: string[];
  request: unknown; // exact body sent to Jev
  response: unknown; // exact body Jev returned (or its error body)
  sdk?: string; // e.g. "decisiondb-python/0.2.0"
};

export async function POST(req: Request) {
  let payload: IngestPayload;
  try {
    payload = (await req.json()) as IngestPayload;
  } catch {
    return Response.json({ error: "body must be JSON" }, { status: 400 });
  }

  // TODO(you): check the API key, validate the shape, then write to Postgres
  // (tables in db/migrations/). For now we just print it.
  console.log("ingest:", JSON.stringify(payload));

  return Response.json({ status: "ok" });
}
